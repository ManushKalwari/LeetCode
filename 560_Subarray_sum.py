# Pattern Summary
# ------------------------------------------------
# Pattern: Prefix Sum + Frequency Counting
# Key insight:
#   For each prefix sum s, the number of subarrays ending at this index
#   that sum to k equals the count of previous prefix sums = s - k.
# Gotcha:
#   Always initialize freq[0] = 1 to count subarrays starting from index 0.

